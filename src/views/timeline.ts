// Messages timeline from a Claude Code transcript JSONL (local only, incremental tail parsing). vscode-free.
// Prompt/reply text is kept in memory for display only; it is never logged or sent anywhere.
import * as fs from 'fs';
import * as path from 'path';
import { countPatch, estimateEdit } from '../collectors/transcriptCollector';

export type ToolStatus = 'run' | 'ok' | 'err';
export interface TlTool {
  id: string; name: string; ts: number; status: ToolStatus; ms?: number;
  /** Short display target: file name, command, pattern, url, or subagent description. */
  target?: string; file?: string; command?: string;
  /** Agent/Task tool: the spawned subagent. */
  agentId?: string; agentType?: string;
}
/** A file changed in a turn. backup: file-history backup of its content before this turn (null = created in it). */
export interface TlFile { path: string; added: number; removed: number; backup?: string | null; /** Edited by a subagent only (no per-message backup). */ sub?: boolean }
export interface TlTurn { line: number; ts: number; endTs: number; prompt?: string;
  /** Set when the user message was only system-injected content (e.g. a background task notification). */
  system?: string; reply?: string; tools: TlTool[]; tokIn: number; tokOut: number; files: TlFile[] }

/**
 * "Revert to before turn `from`": every file changed in that turn or later, with the backup recorded in the
 * earliest such turn (its content before the change). backup null = created at/after the turn (trash it);
 * undefined = no backup recorded (cannot restore). `only` limits to one path.
 */
export function revertPlan(turns: TlTurn[], from: number, only?: string): { path: string; backup?: string | null }[] {
  const out = new Map<string, { path: string; backup?: string | null }>();
  for (let i = Math.max(0, from); i < turns.length; i++) {
    for (const f of turns[i].files) {
      if (only !== undefined && f.path !== only) continue;
      if (!out.has(f.path)) out.set(f.path, { path: f.path, backup: f.backup }); // earliest turn's backup wins
    }
  }
  return [...out.values()];
}

export interface ModelTokens { in: number; out: number; cache: number }
export type Family = 'opus' | 'sonnet' | 'haiku' | 'other';
export function familyOf(model: string): Family {
  const m = model.toLowerCase();
  return m.includes('opus') ? 'opus' : m.includes('sonnet') ? 'sonnet' : m.includes('haiku') ? 'haiku' : 'other';
}
export interface ModelRow { model: string; family: Family; tokens: ModelTokens; share: number; agents: { label: string; active: boolean }[]; active: number }

/** Per-model view: tokens summed across sources, share of all tokens, agents currently on each model. */
export function aggregateModels(sources: { label: string; active: boolean; model?: string; byModel?: Map<string, ModelTokens> }[]): ModelRow[] {
  const rows = new Map<string, ModelRow>();
  const row = (model: string) => {
    let r = rows.get(model);
    if (!r) { r = { model, family: familyOf(model), tokens: { in: 0, out: 0, cache: 0 }, share: 0, agents: [], active: 0 }; rows.set(model, r); }
    return r;
  };
  for (const s of sources) {
    for (const [m, t] of s.byModel ?? []) { const r = row(m); r.tokens.in += t.in; r.tokens.out += t.out; r.tokens.cache += t.cache; }
    if (s.model) { const r = row(s.model); r.agents.push({ label: s.label, active: s.active }); if (s.active) r.active++; }
  }
  const total = [...rows.values()].reduce((x, r) => x + r.tokens.in + r.tokens.out + r.tokens.cache, 0);
  for (const r of rows.values()) r.share = total ? (r.tokens.in + r.tokens.out + r.tokens.cache) / total : 0;
  return [...rows.values()].sort((a, b) => b.active - a.active || b.share - a.share);
}

const MAX_TEXT = 4000;
const HEAD_CHUNK = 4 * 1024 * 1024;
const MAX_BACKLOG = 16 * 1024 * 1024;
const ID_RE = /^[\w-]{1,128}$/;
const CAVEAT = 'Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.';
/** Prompts that are CLI noise: local-command output, command messages, or the full known caveat text. */
export const SKIP_PROMPT = { test: (s: string) => /^\s*(<local-command-|<command-message>)/.test(s) || s.trimStart().startsWith(CAVEAT) };
const INJECTED = ['ide_opened_file', 'ide_selection', 'ide_diagnostics', 'system-reminder', 'task-notification', 'browser_instruction',
  'command-name', 'command-message', 'command-args', 'command-contents', 'local-command-stdout', 'local-command-stderr', 'local-command-caveat',
  'user-prompt-submit-hook', 'bash-input', 'bash-stdout', 'bash-stderr'];
const INJECTED_RE = new RegExp(`<(${INJECTED.join('|')})(\\s[^>]*)?>[\\s\\S]*?</\\1>`, 'g');

/**
 * Task-style subagent label (like Claude Code's agent map). Order: meta.json description → Agent tool input
 * description → first line of the prompt (sanitized, 60 chars) → agentType → 'subagent <id8>'.
 */
export function subagentLabel(o: { metaDescription?: string; description?: string; prompt?: string; agentType?: string; id?: string }): string {
  const one = (x?: string, max = 120) => { const t = x ? cleanPrompt(x).text.split('\n').find((l) => l.trim())?.replace(/\s+/g, ' ').trim() : undefined; return t ? clip(t, max) : undefined; };
  return one(o.metaDescription) ?? one(o.description) ?? one(o.prompt, 60) ?? o.agentType ?? `subagent${o.id ? ' ' + o.id.slice(0, 8) : ''}`;
}

/** Strips system-injected XML-ish blocks from a user message. Empty text + system label = purely injected turn. */
export function cleanPrompt(raw: string): { text: string; system?: string } {
  const text = raw.replace(/\r\n?/g, '\n').replace(INJECTED_RE, '').replace(/\n{3,}/g, '\n\n').trim();
  if (text) return { text };
  const tag = /<([\w-]+)/.exec(raw)?.[1];
  const system = tag === 'task-notification' ? (/<status>\s*(\w+)/.exec(raw)?.[1] === 'failed' ? 'Background task failed' : 'Background task finished')
    : tag === 'bash-input' ? 'Shell command' : tag?.startsWith('ide_') ? 'Editor context' : 'System event';
  return { text: '', system };
}

function rec(v: unknown): Record<string, unknown> | undefined { return v && typeof v === 'object' && !Array.isArray(v) ? v as Record<string, unknown> : undefined; }
function str(v: unknown): string | undefined { return typeof v === 'string' && v ? v : undefined; }
function n(v: unknown): number { return typeof v === 'number' && Number.isFinite(v) && v >= 0 ? v : 0; }
function clip(s: string, max = MAX_TEXT): string { return s.length > max ? s.slice(0, max) + '…' : s; }

/** Short target + jump data for a tool_use input. */
export function toolTarget(name: string, input: unknown): Pick<TlTool, 'target' | 'file' | 'command' | 'agentType'> {
  const i = rec(input) ?? {};
  const file = str(i.file_path) ?? str(i.notebook_path);
  if (file) return { target: path.basename(file), file: file.slice(0, 1024) };
  const cmd = str(i.command);
  if (cmd) return { target: clip(cmd.replace(/\s+/g, ' '), 120), command: cmd.slice(0, 1024) };
  if (name === 'Agent' || name === 'Task') return { target: subagentLabel({ description: str(i.description), prompt: str(i.prompt) }), agentType: str(i.subagent_type)?.slice(0, 64) };
  const t = str(i.pattern) ?? str(i.url) ?? str(i.query) ?? str(i.path) ?? str(i.description);
  return t ? { target: clip(t, 120) } : {};
}

export class TimelineReader {
  turns: TlTurn[] = [];
  /** Bumped whenever turns changed (lets callers skip re-sending identical state). */
  version = 0;
  /** Latest assistant model and token totals per model (whole parsed range). */
  model?: string;
  readonly byModel = new Map<string, ModelTokens>();
  private offset = 0;
  private line = 0;
  private readonly tools = new Map<string, TlTool>();
  private readonly seen = new Set<string>();

  constructor(readonly file: string, private readonly sidechain = false, private readonly maxTurns = 200) {}

  /** Reads newly appended complete lines. Returns true when turns changed. */
  poll(): boolean {
    let size: number;
    try { size = fs.statSync(this.file).size; } catch { return false; }
    if (size < this.offset) { this.offset = 0; this.line = 0; this.turns = []; this.tools.clear(); this.seen.clear(); this.byModel.clear(); }
    if (size === this.offset) return false;
    let fd: number | undefined;
    const before = this.version;
    try {
      fd = fs.openSync(this.file, 'r');
      // ponytail: huge transcripts start at the last 16 MB (lines before only counted for jump-to-line).
      if (this.offset === 0 && size > MAX_BACKLOG) this.skipTo(fd, size - MAX_BACKLOG);
      while (this.offset < size) {
        const len = Math.min(size - this.offset, HEAD_CHUNK);
        const buf = Buffer.alloc(len);
        fs.readSync(fd, buf, 0, len, this.offset);
        const nl = buf.lastIndexOf(0x0a);
        if (nl < 0) { if (len === HEAD_CHUNK) { this.offset += len; continue; } break; }
        this.offset += nl + 1;
        for (const l of buf.subarray(0, nl).toString('utf8').split('\n')) { this.line++; this.apply(l); }
      }
    } catch { /* unreadable: keep what we have */ } finally { if (fd !== undefined) fs.closeSync(fd); }
    if (this.seen.size > 20000) this.seen.clear();
    return this.version !== before;
  }

  private skipTo(fd: number, target: number): void {
    const buf = Buffer.alloc(HEAD_CHUNK);
    let pos = 0;
    while (pos < target) {
      const len = fs.readSync(fd, buf, 0, Math.min(HEAD_CHUNK, target - pos), pos);
      if (len <= 0) break;
      let last = -1;
      for (let i = 0; i < len; i++) if (buf[i] === 0x0a) { this.line++; last = i; }
      pos += len;
      if (pos >= target) { this.offset = last >= 0 ? pos - len + last + 1 : pos; return; }
    }
    this.offset = pos;
  }

  private cwd?: string;
  private readonly est = new Map<string, { path: string; added: number; removed: number }>();

  private fileOf(t: TlTurn, p: string): TlFile {
    const key = p.slice(0, 1024);
    let f = t.files.find((x) => x.path === key);
    if (!f && t.files.length < 200) { f = { path: key, added: 0, removed: 0 }; t.files.push(f); }
    return f ?? { path: key, added: 0, removed: 0 };
  }

  private cur(ts: number): TlTurn {
    let t = this.turns[this.turns.length - 1];
    if (!t) t = this.push({ line: this.line, ts, endTs: ts, tools: [], tokIn: 0, tokOut: 0, files: [] });
    return t;
  }

  private push(t: TlTurn): TlTurn {
    this.turns.push(t);
    while (this.turns.length > this.maxTurns) for (const x of this.turns.shift()!.tools) this.tools.delete(x.id);
    return t;
  }

  /** Applies one JSONL line. Exposed for tests. */
  apply(raw: string): void {
    if (!raw.trim() || raw.length > 4 * 1024 * 1024) return;
    let o: Record<string, unknown> | undefined;
    try { o = rec(JSON.parse(raw)); } catch { return; }
    if (!o || (o.isSidechain === true) !== this.sidechain) return;
    if (typeof o.cwd === 'string') this.cwd = o.cwd;
    if (o.type === 'file-history-delta' && typeof o.trackingPath === 'string') {
      const b = rec(o.backup);
      const name = b?.backupFileName;
      if (!b || (name !== null && typeof name !== 'string')) return;
      const abs = !path.isAbsolute(o.trackingPath) && this.cwd ? path.resolve(this.cwd, o.trackingPath) : o.trackingPath;
      const f = this.fileOf(this.cur(Date.now()), abs);
      if (f.backup === undefined) { f.backup = name as string | null; this.version++; }
      return;
    }
    const msg = rec(o.message);
    if (!msg) return;
    const parsed = typeof o.timestamp === 'string' ? Date.parse(o.timestamp) : NaN;
    const ts = Number.isFinite(parsed) ? parsed : Date.now();
    if (o.type === 'user') this.user(o, msg, ts);
    else if (o.type === 'assistant') this.assistant(msg, ts);
  }

  private user(o: Record<string, unknown>, msg: Record<string, unknown>, ts: number): void {
    const c = msg.content;
    if (Array.isArray(c) && c.some((b) => rec(b)?.type === 'tool_result')) {
      const r = rec(o.toolUseResult);
      for (const b of c) {
        const x = rec(b);
        if (x?.type !== 'tool_result' || typeof x.tool_use_id !== 'string') continue;
        const t = this.tools.get(x.tool_use_id);
        if (!t) continue;
        t.status = x.is_error === true ? 'err' : 'ok';
        t.ms = Math.max(0, ts - t.ts);
        const turn0 = this.turns[this.turns.length - 1];
        if (turn0 && r && typeof r.filePath === 'string' && Array.isArray(r.structuredPatch)) {
          const c = countPatch(r.structuredPatch);
          const f = this.fileOf(turn0, r.filePath);
          f.added += r.type === 'create' && !r.structuredPatch.length && typeof r.content === 'string' ? r.content.split('\n').length : c.added;
          f.removed += c.removed;
        }
        else if (turn0 && x.is_error !== true) {
          // No toolUseResult (subagent transcripts): estimate from the tool input.
          const e = this.est.get(x.tool_use_id);
          if (e) { const f = this.fileOf(turn0, e.path); f.added += e.added; f.removed += e.removed; }
        }
        this.est.delete(x.tool_use_id);
        const aid = str(r?.agentId);
        if (aid && ID_RE.test(aid)) t.agentId = aid;
        const turn = this.turns[this.turns.length - 1];
        if (turn) turn.endTs = Math.max(turn.endTs, ts);
        this.version++;
      }
      return;
    }
    if (o.isMeta === true) return;
    const text = typeof c === 'string' ? c : Array.isArray(c) ? c.map((b) => rec(b)?.type === 'text' ? str(rec(b)!.text) ?? '' : '').join('\n') : '';
    if (!text.trim() || SKIP_PROMPT.test(text)) return;
    const cp = cleanPrompt(text);
    this.push({ line: this.line, ts, endTs: ts, prompt: cp.text ? clip(cp.text) : undefined, system: cp.system, tools: [], tokIn: 0, tokOut: 0, files: [] });
    this.version++;
  }

  private assistant(msg: Record<string, unknown>, ts: number): void {
    const t = this.cur(ts);
    t.endTs = Math.max(t.endTs, ts);
    const u = rec(msg.usage);
    const id = str(msg.id);
    const model = str(msg.model);
    if (model && !model.startsWith('<')) this.model = model.slice(0, 100);
    if (u && (!id || !this.seen.has(id))) {
      if (id) this.seen.add(id);
      if (model && !model.startsWith('<')) {
        const m = this.byModel.get(this.model!) ?? { in: 0, out: 0, cache: 0 };
        m.in += n(u.input_tokens); m.out += n(u.output_tokens); m.cache += n(u.cache_read_input_tokens) + n(u.cache_creation_input_tokens);
        this.byModel.set(this.model!, m);
      }
      t.tokIn += n(u.input_tokens) + n(u.cache_read_input_tokens) + n(u.cache_creation_input_tokens);
      t.tokOut += n(u.output_tokens);
    }
    if (Array.isArray(msg.content)) {
      for (const b of msg.content) {
        const x = rec(b);
        if (x?.type === 'text' && str(x.text) && (t.reply ?? '').length < MAX_TEXT) t.reply = clip(((t.reply ? t.reply + '\n\n' : '') + (x.text as string)).trim());
        if (x?.type === 'tool_use' && typeof x.id === 'string' && typeof x.name === 'string' && !this.tools.has(x.id)) {
          const tool: TlTool = { id: x.id.slice(0, 128), name: x.name.slice(0, 100), ts, status: 'run', ...toolTarget(x.name, x.input) };
          if (t.tools.length < 300) { t.tools.push(tool); this.tools.set(tool.id, tool); }
          const e = estimateEdit(x.name, x.input);
          if (e && this.est.size < 500) this.est.set(tool.id, e);
        }
      }
    }
    this.version++;
  }
}

/** Bounded cache of readers keyed by file path. */
export class Timelines {
  private readonly readers = new Map<string, TimelineReader>();
  constructor(private readonly max = 24) {}

  get(file: string, sidechain = false): TimelineReader {
    let r = this.readers.get(file);
    if (r) { this.readers.delete(file); this.readers.set(file, r); } // LRU touch
    else {
      r = new TimelineReader(file, sidechain);
      this.readers.set(file, r);
      if (this.readers.size > this.max) this.readers.delete(this.readers.keys().next().value as string);
    }
    r.poll();
    return r;
  }

  /** `<dir>/<session>.jsonl` → `<dir>/<session>/subagents/agent-<id>.jsonl` (undefined for unsafe ids). */
  static subagentFile(mainFile: string, agentId: string): string | undefined {
    if (!ID_RE.test(agentId)) return undefined;
    return path.join(path.dirname(mainFile), path.basename(mainFile, '.jsonl'), 'subagents', `agent-${agentId}.jsonl`);
  }

  private readonly metas = new Map<string, { toolUseId?: string; description?: string; agentType?: string }>();

  /** Reads `agent-<id>.meta.json` (cached) so running subagents link to their Agent tool call before it returns. */
  meta(mainFile: string, agentId: string): { toolUseId?: string; description?: string; agentType?: string } | undefined {
    const f = Timelines.subagentFile(mainFile, agentId)?.replace(/\.jsonl$/, '.meta.json');
    if (!f) return undefined;
    let m = this.metas.get(f);
    if (!m) {
      try {
        if (fs.statSync(f).size > 64 * 1024) return undefined;
        const j = rec(JSON.parse(fs.readFileSync(f, 'utf8'))) ?? {};
        m = { toolUseId: str(j.toolUseId), description: str(j.description)?.slice(0, 200), agentType: str(j.agentType)?.slice(0, 64) };
      } catch { return undefined; }
      this.metas.set(f, m);
      if (this.metas.size > 500) this.metas.delete(this.metas.keys().next().value as string);
    }
    return m;
  }

  /** Links Agent tool calls of `reader` to subagent ids found in `<session>/subagents/` (bounded). */
  linkAgents(mainFile: string, reader: TimelineReader): void {
    const unlinked = reader.turns.flatMap((t) => t.tools).filter((t) => (t.name === 'Agent' || t.name === 'Task') && !t.agentId);
    if (!unlinked.length) return;
    let names: string[] = [];
    try { names = fs.readdirSync(path.join(path.dirname(mainFile), path.basename(mainFile, '.jsonl'), 'subagents')); } catch { return; }
    for (const nm of names.slice(-300)) {
      const id = /^agent-([\w-]{1,128})\.meta\.json$/.exec(nm)?.[1];
      const m = id ? this.meta(mainFile, id) : undefined;
      const t = m?.toolUseId ? unlinked.find((x) => x.id === m.toolUseId) : undefined;
      if (t && id) { t.agentId = id; reader.version++; }
    }
  }

  /** Agent tool call that spawned `agentId` in the main transcript, plus the subagent's own tools/tokens. */
  agentDetails(mainFile: string, agentId: string): { description?: string; type?: string; tools: TlTool[]; tokens: number; ms?: number; model?: string; byModel?: Map<string, ModelTokens>; files: TlFile[] } | undefined {
    const main = this.get(mainFile);
    const m = this.meta(mainFile, agentId);
    const all = main.turns.flatMap((t) => t.tools);
    const call = all.find((x) => x.agentId === agentId) ?? (m?.toolUseId ? all.find((x) => x.id === m.toolUseId) : undefined);
    const sub = Timelines.subagentFile(mainFile, agentId);
    const r = sub && fs.existsSync(sub) ? this.get(sub, true) : undefined;
    if (!call && !r && !m) return undefined;
    const turns = r?.turns ?? [];
    return {
      description: m?.description ?? call?.target, type: call?.agentType ?? m?.agentType, ms: call?.ms, model: r?.model, byModel: r?.byModel, files: turns.flatMap((t) => t.files),
      tools: turns.flatMap((t) => t.tools).slice(-100),
      tokens: turns.reduce((s, t) => s + t.tokIn + t.tokOut, 0)
    };
  }
}

export interface FamilyShare { family: Family; share: number; tokens: ModelTokens; agents: { label: string; active: boolean }[]; active: number }
/** Per-family token shares as whole percents that sum to exactly 100 (largest remainder); all 0 when there are no tokens. */
export function familyShares(rows: ModelRow[]): FamilyShare[] {
  const m = new Map<Family, FamilyShare>();
  for (const r of rows) {
    const f = m.get(r.family) ?? { family: r.family, share: 0, tokens: { in: 0, out: 0, cache: 0 }, agents: [], active: 0 };
    f.tokens.in += r.tokens.in; f.tokens.out += r.tokens.out; f.tokens.cache += r.tokens.cache;
    f.agents.push(...r.agents); f.active += r.active; m.set(r.family, f);
  }
  const fs = [...m.values()];
  const tot = (f: FamilyShare) => f.tokens.in + f.tokens.out + f.tokens.cache;
  const all = fs.reduce((x, f) => x + tot(f), 0);
  if (all > 0) {
    const raw = fs.map((f) => (tot(f) / all) * 100);
    fs.forEach((f, i) => { f.share = Math.floor(raw[i]); });
    let left = 100 - fs.reduce((x, f) => x + f.share, 0);
    [...fs.keys()].sort((a, b) => (raw[b] - Math.floor(raw[b])) - (raw[a] - Math.floor(raw[a]))).forEach((i) => { if (left-- > 0) fs[i].share++; });
  }
  const order: Family[] = ['opus', 'sonnet', 'haiku', 'other'];
  return fs.sort((a, b) => order.indexOf(a.family) - order.indexOf(b.family));
}
